from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer, Image
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
import io
import os

def generate_patient_pdf(patient, diagnosis):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter)
    elements = []
    styles = getSampleStyleSheet()

    # Header
    title_style = ParagraphStyle('Title', parent=styles['Heading1'], alignment=1, textColor=colors.darkblue)
    elements.append(Paragraph("IshtirafAI Medical Report", title_style))
    elements.append(Spacer(1, 20))

    # Patient Info
    elements.append(Paragraph(f"<b>Patient Name:</b> {patient.name}", styles['Normal']))
    elements.append(Paragraph(f"<b>Age/Gender:</b> {patient.age} / {patient.gender}", styles['Normal']))
    elements.append(Paragraph(f"<b>Contact:</b> {patient.contact}", styles['Normal']))
    elements.append(Paragraph(f"<b>Report Date:</b> {diagnosis.timestamp.strftime('%Y-%m-%d %H:%M')}", styles['Normal']))
    elements.append(Spacer(1, 20))

    # Diagnosis Result
    diag_color = "green" if "NORMAL" in diagnosis.diagnosis_result else "red"
    diag_style = ParagraphStyle('Diagnosis', parent=styles['Heading2'], textColor=getattr(colors, diag_color, colors.black))
    elements.append(Paragraph(f"Diagnosis: {diagnosis.diagnosis_result}", diag_style))
    
    elements.append(Paragraph(f"<b>Confidence:</b> {diagnosis.confidence}%", styles['Normal']))
    elements.append(Paragraph(f"<b>Risk Score:</b> {diagnosis.risk_score}/10", styles['Normal']))
    elements.append(Spacer(1, 10))
    
    # Clinical Details Table
    data = [
        ["Parameter", "Value"],
        ["Path Used", diagnosis.path_used],
        ["RMS Value", f"{diagnosis.rms_value:.3f}"],
        ["Chest Pain", "Yes" if diagnosis.sym_chest_pain else "No"],
        ["Shortness of Breath", "Yes" if diagnosis.sym_shortness else "No"],
        ["History of Heart Disease", "Yes" if diagnosis.sym_history else "No"],
        ["Patient Mode", diagnosis.patient_mode],
        ["Organ Mode", diagnosis.organ_mode]
    ]
    
    t = Table(data)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.grey),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
        ('BACKGROUND', (0, 1), (-1, -1), colors.beige),
        ('GRID', (0, 0), (-1, -1), 1, colors.black)
    ]))
    elements.append(t)
    elements.append(Spacer(1, 20))

    # Recommendation
    elements.append(Paragraph("<b>Clinical Recommendation:</b>", styles['Heading3']))
    elements.append(Paragraph(diagnosis.recommendation, styles['Normal']))
    
    elements.append(Spacer(1, 40))
    elements.append(Paragraph("<i>Generated by IshtirafAI - AI Assisted Diagnostic System</i>", styles['Italic']))

    doc.build(elements)
    buffer.seek(0)
    return buffer
